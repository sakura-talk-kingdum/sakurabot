/**
 * Finds the birthdays of a day.
 *
 * @param month - The month, starting at 1
 * @param date - The day of the month
 * @returns The mention or name of every person that has a birthday
 */
export function findBirthdays(month: number, date: number): { id: string | null; name: string }[] {
	const key = `${month}/${date}`;
	const entries: { id: string | null; name: string }[] = [];

	for (const line of BIRTHDAY_LIST.trim().split('\n')) {
		// Match the whole date token so that `1/2` does not match `1/20`
		const [day, ...rest] = line.trim().split(/\s+/);
		if (day !== key && !day?.startsWith(`${key}/`)) {
			continue;
		}

		const name = rest.join(' ').trim();
		const id = /<@!?(\d+)>/.exec(name)?.[1] ?? null;
		entries.push({ id, name });
	}

	return entries;
}
